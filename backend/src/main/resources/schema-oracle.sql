-- Oracle schema for local development (XE)
-- Apply manually when running with profile: local-oracle

CREATE TABLE users (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wechat_unionid VARCHAR2(128) NOT NULL,
  wechat_openid VARCHAR2(128),
  role VARCHAR2(32) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL
);

CREATE UNIQUE INDEX uk_users_unionid ON users(wechat_unionid);

CREATE TABLE quota_account (
  user_id NUMBER(19) PRIMARY KEY,
  ocr_total NUMBER(10) NOT NULL,
  ocr_used NUMBER(10) NOT NULL,
  ocr_refunded NUMBER(10) NOT NULL,
  translate_total NUMBER(10) NOT NULL,
  translate_used NUMBER(10) NOT NULL,
  translate_refunded NUMBER(10) NOT NULL,
  updated_at TIMESTAMP(3) NOT NULL,
  CONSTRAINT fk_quota_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE translation_task (
  task_id VARCHAR2(32) PRIMARY KEY,
  user_id NUMBER(19) NOT NULL,
  source_filename VARCHAR2(255) NOT NULL,
  source_type VARCHAR2(16) NOT NULL,
  source_size NUMBER(19) NOT NULL,
  source_path VARCHAR2(512),
  status VARCHAR2(32) NOT NULL,
  stage VARCHAR2(32) NOT NULL,
  retry_count NUMBER(10) NOT NULL,
  error_code VARCHAR2(64),
  error_message VARCHAR2(255),
  created_at TIMESTAMP(3) NOT NULL,
  started_at TIMESTAMP(3),
  finished_at TIMESTAMP(3),
  updated_at TIMESTAMP(3) NOT NULL,
  CONSTRAINT fk_task_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_task_user_created ON translation_task(user_id, created_at);
CREATE INDEX idx_task_status_created ON translation_task(status, created_at);

CREATE TABLE task_artifact (
  task_id VARCHAR2(32) PRIMARY KEY,
  source_path VARCHAR2(512),
  preview_path VARCHAR2(512),
  output_path VARCHAR2(512),
  expires_at TIMESTAMP(3) NOT NULL,
  created_at TIMESTAMP(3) NOT NULL,
  CONSTRAINT fk_artifact_task FOREIGN KEY (task_id) REFERENCES translation_task(task_id)
);

CREATE TABLE audit_log (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19),
  task_id VARCHAR2(32),
  action VARCHAR2(64) NOT NULL,
  ip VARCHAR2(64),
  user_agent VARCHAR2(255),
  detail VARCHAR2(255),
  created_at TIMESTAMP(3) NOT NULL
);

CREATE INDEX idx_audit_user_created ON audit_log(user_id, created_at);
CREATE INDEX idx_audit_task_created ON audit_log(task_id, created_at);
